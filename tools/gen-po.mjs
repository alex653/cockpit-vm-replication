#!/usr/bin/env node
/* Generates po/<lang>.po files: the msgid structure comes from po/ru.po
 * (the reference language, kept in sync with src/ by check-po.mjs), the
 * translations come from tools/po-data/<lang>.json.
 *
 * JSON key format:
 *   plain string entry  ->  key: "ctx\x04msgid" or just "msgid"
 *   plural entry        ->  key: "msgid", value: array with one string
 *                           per plural form (length must equal nplurals)
 * Exits non-zero when a translation is missing or malformed. */

import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const PODIR = path.join(ROOT, "po");
const DATA = path.join(ROOT, "tools", "po-data");

/* target languages and their Plural-Forms headers */
const LANGS = {
    de: { name: "German", plurals: "nplurals=2; plural=(n != 1);" },
    fr: { name: "French", plurals: "nplurals=2; plural=(n > 1);" },
    es: { name: "Spanish", plurals: "nplurals=2; plural=(n != 1);" },
    it: { name: "Italian", plurals: "nplurals=2; plural=(n != 1);" },
    pt: { name: "Portuguese", plurals: "nplurals=2; plural=(n != 1);" },
    pl: { name: "Polish", plurals: "nplurals=3; plural=(n==1 ? 0 : n%10>=2 && n%10<=4 && (n%100<10 || n%100>=20) ? 1 : 2);" },
    uk: { name: "Ukrainian", plurals: "nplurals=3; plural=(n%10==1 && n%100!=11 ? 0 : n%10>=2 && n%10<=4 && (n%100<10 || n%100>=20) ? 1 : 2);" },
    zh: { name: "Simplified Chinese", plurals: "nplurals=1; plural=0;" },
    ja: { name: "Japanese", plurals: "nplurals=1; plural=0;" },
};

const npluralsOf = formula => Number(formula.match(/nplurals=(\d)/)[1]);

/* parse po/ru.po into ordered entries (the translation of ru itself is kept) */
function parseReference() {
    const entries = [];
    let ctx = null, msgid = null, pluralMsgid = null, isPlural = false;
    const flush = () => {
        if (msgid === null) return; /* nothing pending: keep ctx for the entry being started */
        entries.push({ ctx, msgid, pluralMsgid: isPlural ? pluralMsgid : null });
        ctx = null; msgid = null; pluralMsgid = null; isPlural = false;
    };
    const lines = fs.readFileSync(path.join(PODIR, "ru.po"), "utf8").split("\n");
    for (let i = 0; i < lines.length; i++) {
        const line = lines[i];
        if (line.startsWith("#") || line.trim() === "") continue;
        let m;
        if ((m = line.match(/^msgctxt "((?:[^"\\]|\\.)*)"/))) { flush(); ctx = JSON.parse(`"${m[1]}"`); continue; }
        if ((m = line.match(/^msgid "((?:[^"\\]|\\.)*)"/))) {
            if (m[1] === "") { // header block — skip to its msgstr and resume
                while (i < lines.length && !lines[i].startsWith("msgstr")) i++;
                continue;
            }
            flush();
            msgid = JSON.parse(`"${m[1]}"`);
            continue;
        }
        if ((m = line.match(/^msgid_plural "((?:[^"\\]|\\.)*)"/))) {
            pluralMsgid = JSON.parse(`"${m[1]}"`);
            isPlural = true;
            continue;
        }
    }
    flush();
    return entries;
}

const entries = parseReference();
console.log(`reference ru.po: ${entries.length} entries (${entries.filter(e => e.pluralMsgid).length} plural, ${entries.filter(e => e.ctx).length} with context)`);

const key = (ctx, msgid) => (ctx ? ctx + "\u0004" : "") + msgid;
const poEscape = s => s.replace(/\\/g, "\\\\").replace(/"/g, '\\"');

let failed = 0;

for (const [lang, meta] of Object.entries(LANGS)) {
    const file = path.join(DATA, `${lang}.json`);
    if (!fs.existsSync(file)) {
        console.error(`${lang}: missing tools/po-data/${lang}.json`);
        failed++;
        continue;
    }
    const dict = JSON.parse(fs.readFileSync(file, "utf8"));
    const n = npluralsOf(meta.plurals);
    const missing = [], bad = [];

    const po = [
        `# ${meta.name} translations for the cockpit-vm-replication package.`,
        `# Generated by tools/gen-po.mjs from tools/po-data/${lang}.json — edit the JSON, not this file.`,
        "#",
        'msgid ""',
        "msgstr \"\"",
        '"Project-Id-Version: cockpit-vm-replication 2.0.0\\n"',
        '"PO-Revision-Date: 2026-10-27 21:00+0000\\n"',
        `"Language: ${lang}\\n"`,
        '"MIME-Version: 1.0\\n"',
        '"Content-Type: text/plain; charset=UTF-8\\n"',
        '"Content-Transfer-Encoding: 8bit\\n"',
        `"Plural-Forms: ${meta.plurals}\\n"`,
        "",
    ];

    for (const e of entries) {
        const k = e.pluralMsgid ? e.msgid : key(e.ctx, e.msgid);
        const val = dict[k];
        const where = e.ctx ? `[${e.ctx}] ` : "";
        if (val === undefined) {
            missing.push(`${where}${JSON.stringify(e.msgid)}`);
            continue;
        }
        if (e.pluralMsgid) {
            if (!Array.isArray(val) || val.length !== n) {
                bad.push(`${JSON.stringify(e.msgid)}: expected array of ${n} plural forms, got ${Array.isArray(val) ? val.length : typeof val}`);
                continue;
            }
            po.push("#: src/00-generated.po",
                `msgid "${poEscape(e.msgid)}"`,
                `msgid_plural "${poEscape(e.pluralMsgid)}"`,
                ...val.map((s, i) => `msgstr[${i}] "${poEscape(s)}"`),
                "");
        } else {
            if (typeof val !== "string" || val === "") {
                bad.push(`${where}${JSON.stringify(e.msgid)}: not a non-empty string`);
                continue;
            }
            po.push("#: src/00-generated.po",
                e.ctx ? `msgctxt "${poEscape(e.ctx)}"` : null,
                `msgid "${poEscape(e.msgid)}"`,
                `msgstr "${poEscape(val)}"`,
                "");
        }
    }

    if (missing.length || bad.length) {
        console.error(`${lang}: ${missing.length} missing, ${bad.length} malformed`);
        for (const m of missing) console.error(`  missing: ${m}`);
        for (const b of bad) console.error(`  malformed: ${b}`);
        failed++;
        continue;
    }

    fs.writeFileSync(path.join(PODIR, `${lang}.po`),
                     po.filter(l => l !== null).join("\n") + "\n", "utf8");
    console.log(`${lang}: wrote po/${lang}.po (${entries.length} entries)`);
}

process.exit(failed ? 1 : 0);
